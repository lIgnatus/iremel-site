// Записывает в каждое изображение его происхождение
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const tool = process.argv[2];
const sets = [
  ['public/img', 'Origin: photo of the Iremel guest house complex, from iremel.org and its LitePMS booking page, resized.'],
  ['public/video', 'Origin: frame from a CC BY video, author and link listed in the site footer.'],
  ['public/terrain', 'Origin: generated by tools/make-terrain.mjs from Copernicus DEM GLO-30 and OpenStreetMap rivers.'],
];
let done = 0, failed = 0;
for (const [dir, prompt] of sets) {
  for (const f of fs.readdirSync(path.join(root, dir))) {
    if (!f.endsWith('.webp')) continue;
    const rel = `${dir}/${f}`;
    const r = spawnSync('cmd.exe', ['/c', tool, 'embed-prompt', rel, '--prompt', prompt], { cwd: root, encoding: 'utf8' });
    if (r.status) { failed++; console.log(rel, (r.stderr || r.stdout).slice(0, 200)); } else done++;
  }
}
console.log('готово', done, 'ошибок', failed);
